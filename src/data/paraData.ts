// Helper to fetch all verses of a specified Para (Juz) with both Arabic and English translation
export async function fetchParaVerses(paraNumber: number): Promise<ParaAyah[]> {
  try {
    const [arabicRes, englishRes] = await Promise.all([
      fetch(`https://api.alquran.cloud/v1/juz/${paraNumber}/quran-uthmani`),
      fetch(`https://api.alquran.cloud/v1/juz/${paraNumber}/en.sahih`)
    ]);

    if (!arabicRes.ok || !englishRes.ok) {
      throw new Error(`Failed to fetch Para ${paraNumber} verses from API`);
    }

    const [arabicData, englishData] = await Promise.all([
      arabicRes.json(),
      englishRes.json()
    ]);

    const arabicAyahs = arabicData?.data?.ayahs || [];
    const englishAyahs = englishData?.data?.ayahs || [];

    return arabicAyahs.map((ayah: any, index: number): ParaAyah => {
      const eng = englishAyahs[index];
      return {
        number: ayah.number,
        numberInSurah: ayah.numberInSurah,
        surahNumber: ayah.surah.number,
        surahNameArabic: ayah.surah.name,
        surahNameEnglish: ayah.surah.englishName,
        surahEnglishTranslation: ayah.surah.englishNameTranslation,
        textArabic: ayah.text,
        textEnglish: eng?.text || "",
        juz: paraNumber,
        page: ayah.page,
        ruku: ayah.ruku,
        isSajda: typeof ayah.sajda === 'boolean' ? ayah.sajda : !!ayah.sajda
      };
    });
  } catch (error) {
    console.warn(`Fallback for Para ${paraNumber}:`, error);
    if (paraNumber === 1) {
      return SAMPLE_JUZ_1_AYAHS;
    }
    // Return graceful placeholder if offline
    const meta = PARA_LIST[paraNumber - 1];
    return [
      {
        number: 1,
        numberInSurah: 1,
        surahNumber: meta ? meta.startSurahNumber : 1,
        surahNameArabic: meta ? meta.startSurahName : "سورة",
        surahNameEnglish: meta ? meta.startSurahName : "Surah",
        surahEnglishTranslation: "",
        textArabic: "بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ",
        textEnglish: "In the name of Allah, the Entirely Merciful, the Especially Merciful.",
        juz: paraNumber
      }
    ];
  }
}
